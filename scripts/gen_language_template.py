"""Writes languages/template.txt: every text the port prints itself, for translators.

The texts are the English halves of the tr("french", "english") calls of the
game's sources (not the editor's), and the tables handed to tr: the
controller's actions and buttons (src/core/pad_config.hpp) and the item names
(src/core/dtable.cpp). The format is described in src/core/translation.hpp.

Usage: python scripts/gen_language_template.py [--check]
--check only compares the file with what it would write, and exits with 1 when
they differ (a ctest).
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
template = root / 'languages' / 'template.txt'

LIT = r'"(?:[^"\\]|\\.)*"'
LITS = rf'{LIT}(?:\s*{LIT})*'
TR = re.compile(rf'\btr\(\s*({LITS})\s*,\s*({LITS})\s*\)', re.S)

HEADER = '''\
# Language file of the Crusader: No Regret port: the template.
#
# Copy this file to "<language>.txt" in this folder (pt-br.txt for example, no
# spaces), fill in the translations, then pick the language in the game:
# options, "+" (enhancements), game, language. Language files are read again
# each time they are picked there.
#
# - "@name": the name of the language, as the game shows it.
# - The other lines: an English text, "=", its translation. An empty
#   translation keeps the original text. "\\n" is a line break.
# - Keep the "%" codes of the English text (%u, %02u, %ld), in the same order:
#   the game ignores a translation that changes them.
# - The file is UTF-8. The game turns it into code page 850, the code page of
#   its fonts; the fonts of the game data must have the letters used (the
#   menus of the port use capitals without accents).
# - The texts of the game data (FLX files, movie subtitles, pictures) are not
#   here: a translation changes those files.
# - "# FR:" lines give the French texts of the port, to help with the meaning.
#
# This file is generated by scripts/gen_language_template.py.

@name =
'''

NOTES = {
    'src/engine/ui/weasel_gump.cpp': "Weasel's shop, No Remorse only",
    'src/engine/ui/enhancements_screen.cpp': 'enhancements window',
    'src/engine/ui/gamepad_screen.cpp': 'controller screen',
    'src/engine/ui/load_screen.cpp': 'load and save screen',
    'src/engine/ui/computer_gump.hpp': 'computer terminals',
    'src/engine/ui/options_screen.cpp': 'options screen',
    'src/engine/ui/status_bar.cpp': 'status bar',
    'src/engine/world/pickup_list.cpp': 'items picked up',
    'src/engine/world/player_commands.cpp': 'messages',
    'src/game/game.cpp': 'main menu and saves',
}


def c_string(text):
    """The bytes of adjacent C string literals, as code page 850 text."""
    out = b''
    for part in re.findall(LIT, text):
        body, i = part[1:-1], 0
        while i < len(body):
            if body[i] != '\\':
                out += body[i].encode('ascii')
                i += 1
            elif body[i + 1] == 'x':
                digits = re.match(r'[0-9a-fA-F]{1,2}', body[i + 2:]).group(0)
                out += bytes([int(digits, 16)])
                i += 2 + len(digits)
            else:
                out += {'n': b'\n', 't': b'\t', '"': b'"', "'": b"'", '\\': b'\\'}[body[i + 1]]
                i += 2
    return out.decode('cp850')


def string_array(source, name):
    match = re.search(rf'\b{name}\s*=\s*\{{(.*?)\}};', source, re.S)
    if not match:
        sys.exit(f'{name} not found')
    return [c_string(s) for s in re.findall(LIT, match.group(1))]


def escape(text):
    return text.replace('\\', '\\\\').replace('\n', '\\n')


def sections():
    """(title, [(english, [french...])]) in order."""
    found = []
    for path in sorted(root.glob('src/**/*.[ch]pp')):
        rel = path.relative_to(root).as_posix()
        if rel.startswith('src/editor/'):
            continue
        texts = {}
        for m in TR.finditer(path.read_text(encoding='utf-8')):
            texts.setdefault(c_string(m.group(2)), []).append(c_string(m.group(1)))
        if texts:
            title = f'{NOTES[rel]} ({rel})' if rel in NOTES else rel
            found.append((title, list(texts.items())))

    pad = (root / 'src/core/pad_config.hpp').read_text(encoding='utf-8')
    actions = re.search(r'kPadActions = \{\{(.*?)\}\};', pad, re.S).group(1)
    texts = {}
    for fr, en in re.findall(rf'\{{\s*({LIT})\s*,\s*({LIT})', actions):
        texts.setdefault(c_string(en), []).append(c_string(fr))
    for fr, en in zip(string_array(pad, 'kPadButtonLabels'), string_array(pad, 'kPadButtonLabelsEn')):
        texts.setdefault(en, []).append(fr)
    found.append(('controller actions and buttons (src/core/pad_config.hpp)', list(texts.items())))

    dtable = (root / 'src/core/dtable.cpp').read_text(encoding='utf-8')
    texts = {}
    for table in ('kRegretItemNames', 'kRegretAmmoNames', 'kRegretFamily12Names'):
        for en in string_array(dtable, table):
            texts.setdefault(en, [])
    found.append(('item names, No Regret (src/core/dtable.cpp)', list(texts.items())))
    texts = {}
    for table in ('kItemNames', 'kAmmoNames', 'kFamily12Names'):
        for fr, en in zip(string_array(dtable, table), string_array(dtable, table + 'Us')):
            texts.setdefault(en, []).append(fr)
    found.append(('item names, No Remorse (src/core/dtable.cpp)', list(texts.items())))
    return found


def generate():
    found = sections()
    # The French texts of an English one, from every place it is used.
    french = {}
    for _, texts in found:
        for en, frs in texts:
            french.setdefault(en, []).extend(frs)
    out = HEADER
    # Button names (A, LB...) are not translated.
    seen = {'INVALID'} | {en for en in french if len(en) <= 2}
    for title, texts in found:
        lines = []
        for en, _ in texts:
            if en in seen:
                continue
            seen.add(en)
            for fr in dict.fromkeys(french[en]):
                if fr != en:
                    lines.append(f'# FR: {escape(fr)}')
            lines.append(f'{escape(en)} =')
        if lines:
            out += f'\n# --- {title}\n' + '\n'.join(lines) + '\n'
    return out


def main():
    text = generate()
    if '--check' in sys.argv[1:]:
        current = template.read_text(encoding='utf-8') if template.exists() else ''
        if current != text:
            print(f'{template} is out of date: run python scripts/gen_language_template.py')
            return 1
        return 0
    template.parent.mkdir(exist_ok=True)
    template.write_text(text, encoding='utf-8', newline='\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
