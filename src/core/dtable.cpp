NpcTypes NpcTypes::load(const std::filesystem::path& dtable_flx) {
    const FlexArchive flex = FlexArchive::open(dtable_flx);
    const auto entry = flex.entry(0);
    if (entry.size() < kRecordSize * kRecords) {
        throw std::runtime_error("DTABLE.FLX entry 0 too short");
    }
    NpcTypes t;
    t.data_.assign(entry.begin(), entry.begin() + kRecordSize * kRecords);
    return t;
}

// @orig 1130:010A
int NpcTypes::index(std::uint16_t shape) const {
    for (int i = 0; i < kRecords; ++i) {
        const std::size_t at = i * kRecordSize + 0x3E;
        if ((data_[at] | data_[at + 1] << 8) == shape) return i;
    }
    return -1;
}

std::uint16_t NpcTypes::word(int index, std::size_t at) const {
    if (index < 0 || index >= kRecords || at + 2 > kRecordSize) return 0;
    const std::size_t p = index * kRecordSize + at;
    return static_cast<std::uint16_t>(data_[p] | data_[p + 1] << 8);
}

std::uint16_t NpcTypes::max_hp(int index) const {
    if (index < 0 || index >= kRecords) return 0;
    const std::size_t at = index * kRecordSize + 2;
    return static_cast<std::uint16_t>(data_[at] | data_[at + 1] << 8);
}

